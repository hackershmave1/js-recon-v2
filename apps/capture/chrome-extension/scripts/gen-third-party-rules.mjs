// gen-third-party-rules.mjs — refreshes modules/third-party-rules.js from the ONE source of the
// built-in third-party rules, apps/platform/src/recon/findings/third_party_rules.json (ADR-0010).
// Run after editing that JSON: `node scripts/gen-third-party-rules.mjs`. The output is committed
// (the worker loads modules unbundled), and tests/test_third_party_rules.mjs fails if it drifts.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE = resolve(here, '../../../platform/src/recon/findings/third_party_rules.json');
export const TARGET = resolve(here, '../modules/third-party-rules.js');

export function renderModule(doc) {
  const hosts = [...new Set(Object.values(doc.hosts).flat())].sort();
  const lines = (items) => items.map((item) => `  ${JSON.stringify(item)},`).join('\n');
  return `// third-party-rules.js — GENERATED by scripts/gen-third-party-rules.mjs from
// apps/platform/src/recon/findings/third_party_rules.json. Do not edit by hand: edit the JSON and
// regenerate (tests/test_third_party_rules.mjs fails on drift). ADR-0010.
//
// HOSTS: a host entry drops a script's host and its subdomains, unless the researcher typed that host
// into the scope (the caller checks scope). FILE_PATTERNS: globs matched against the URL path on ANY
// host, scoped or not (a library file on the app's own host is still a library).

export const NOISE_HOSTS = new Set([
${lines(hosts)}
]);

export const FILE_PATTERNS = [
${lines(doc.file_patterns)}
];
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(TARGET, renderModule(JSON.parse(readFileSync(SOURCE, 'utf8'))));
  console.log(`wrote ${TARGET}`);
}
